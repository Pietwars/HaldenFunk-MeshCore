#!/usr/bin/env python3
"""Vereinfachte Karten für das T-Deck-Plus-Standalone (Issue #35) aus den Webkarten erzeugen (eine Quelle).

Quelle: web/map/*.json.gz (© OpenStreetMap-Mitwirkende, ODbL 1.0, siehe web/map/ODbL-1.0.txt).
Ziel:   examples/companion_radio/ui-brand/MapData.h (im Flash der Firmware).

Vereinfacht für 320 × 240: nur Gewässer (Flächenumriss, Bach, Fluss), Straßen, Hauptstraßen und Bahn; Gebäude,
Felder und Wald fallen weg. Linien werden mit Douglas-Peucker auf ca. 0,7 Pixel bei vierfacher Vergrößerung der
Übersicht vereinfacht. Punkte: Orte, Apotheke/Arzt, Wasser (wie die Legende der Webkarte).
Koordinaten: ganzzahlig in 2·10⁻⁵ Grad relativ zur linken unteren Ecke der Karte (uint16).

  python3 tools/gen_device_map.py          schreibt MapData.h
  python3 tools/gen_device_map.py --check  prüft, ob MapData.h zu den Webkarten passt (CI)
"""
import gzip, json, math, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'examples/companion_radio/ui-brand/MapData.h'
# Reihenfolge wie die Auswahl in web/index.html (#mapsel)
MAPS = ['mansfelder-land', 'eisleben', 'mansfeld-hettstedt', 'sangerhausen', 'kelbra-kyffhaeuser']
STYLES = ['wa', 's', 'w', 'r', 'rw', 'h']          # gezeichnet in dieser Reihenfolge (wie ORDER im Web)
KINDS = {'apo': 1, 'med': 1, 'h2o': 2}              # 1 Apotheke/Arzt, 2 Wasser; Orte: 3 Stadt, 4 Dorf/Ortsteil, 5 sonstige
UNIT = 2                                            # 2·10⁻⁵ Grad
W, H = 320, 224                                     # Kartenfläche unter der Navigationsleiste


def cp437(text):
    table = {'·': 0xFA, 'ä': 0x84, 'ö': 0x94, 'ü': 0x81, 'Ä': 0x8E, 'Ö': 0x99, 'Ü': 0x9A, 'ß': 0xE1, 'é': 0x82, 'è': 0x8A}
    out = ''
    for ch in text:
        if 32 <= ord(ch) < 127 and ch not in '"\\':
            out += ch
        elif ch in table:
            out += '\\x%02x' % table[ch]
        elif ch in '"\\':
            out += '\\' + ch
        elif ch in '–—':
            out += '-'
        else:
            out += '?'
    # keep hex escapes from swallowing following hex digits
    return out.replace('\\x', '\\x').replace('"', '"')


def esc(text):
    s = cp437(text)
    res, i = '', 0
    while i < len(s):
        if s.startswith('\\x', i):
            res += s[i:i + 4]; i += 4
            if i < len(s) and s[i] in '0123456789abcdefABCDEF':
                res += '""'
            continue
        res += s[i]; i += 1
    return res


def rdp(pts, eps):
    if len(pts) < 3:
        return pts
    keep = [False] * len(pts); keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        ax, ay = pts[a]; bx, by = pts[b]
        dx, dy = bx - ax, by - ay; L = math.hypot(dx, dy)
        best, idx = -1, -1
        for i in range(a + 1, b):
            px, py = pts[i]
            d = math.hypot(px - ax, py - ay) if L == 0 else abs(dy * (px - ax) - dx * (py - ay)) / L
            if d > best:
                best, idx = d, i
        if best > eps:
            keep[idx] = True; stack += [(a, idx), (idx, b)]
    return [p for p, k in zip(pts, keep) if k]


def labels():
    """Kartennamen wie in der Kartenauswahl der Weboberfläche (<select id="mapsel">)."""
    import re
    web = (ROOT / 'web/index.html').read_text()
    sel = re.search(r'<select id="mapsel">(.*?)</select>', web).group(1)
    return dict(re.findall(r'<option value="([a-z0-9-]+)">([^<]+)</option>', sel))


def build():
    names = labels()
    lines_out = ['#pragma once', '// Generated by tools/gen_device_map.py from web/map/*.json.gz. Do not edit.',
                 '// Kartendaten: (c) OpenStreetMap-Mitwirkende, ODbL 1.0 (web/map/ODbL-1.0.txt).',
                 '#include <stdint.h>', 'namespace devmap {',
                 'enum Style : uint8_t { WATER_AREA = 0, STREAM, RIVER, ROAD, RAIL, MAIN_ROAD, STYLE_COUNT };',
                 'enum PointKind : uint8_t { PHARMACY = 1, WATER = 2, TOWN = 3, VILLAGE = 4, PLACE = 5 };',
                 'struct Line { uint8_t style; uint16_t n; uint32_t at; uint16_t x0, y0, x1, y1; };',
                 'struct Point { uint8_t kind; uint16_t x, y; const char *name; };',
                 'struct Map { const char *key; const char *name; int32_t lon0, lat0; uint16_t w, h;',
                 '  uint16_t vx0, vy0, vx1, vy1; const Line *lines; uint16_t nlines; const uint16_t *xy;',
                 '  const Point *points; uint16_t npoints; };', 'constexpr int UNIT = %d;  // 1e-5 degrees per step' % UNIT]
    infos = []; total = 0
    for key in MAPS:
        d = json.load(gzip.open(ROOT / 'web/map' / (key + '.json.gz')))
        bb = d['bbox']; view = d.get('view') or bb
        # origin: lower left corner of the bbox or of the data, whichever is further out (lines may overhang)
        lon0, lat0 = math.floor(bb[0] * 1e5), math.floor(bb[1] * 1e5)
        for l in d['l']:
            x, y = l[1], l[2]; lon0 = min(lon0, x); lat0 = min(lat0, y)
            for i in range(3, len(l), 2):
                x += l[i]; y += l[i + 1]; lon0 = min(lon0, x); lat0 = min(lat0, y)
        lon0 -= UNIT; lat0 -= UNIT
        k = math.cos((bb[1] + bb[3]) / 2 * math.pi / 180)
        ppd = min(W / ((view[2] - view[0]) * k), H / (view[3] - view[1]))   # pixel per degree latitude at fit
        eps_deg = 0.7 / (ppd * 4)
        eps = eps_deg * 1e5 / UNIT
        xy, lines = [], []
        for style in STYLES:
            for l in d['l']:
                if l[0] != style:
                    continue
                x, y = l[1], l[2]; pts = [(x, y)]
                for i in range(3, len(l), 2):
                    x += l[i]; y += l[i + 1]; pts.append((x, y))
                pts = [((px - lon0) / UNIT, (py - lat0) / UNIT) for px, py in pts]
                # x is longitude; distances in lon are shorter by cos(lat)
                scaled = [(px * k, py) for px, py in pts]
                keep = rdp(scaled, eps)
                q = []
                for px, py in keep:
                    p = (round(px / k), round(py))
                    if not q or q[-1] != p:
                        q.append(p)
                if len(q) < 2:
                    continue
                for px, py in q:
                    assert 0 <= px < 65536 and 0 <= py < 65536, (key, px, py)
                xs = [p[0] for p in q]; ys = [p[1] for p in q]
                lines.append((STYLES.index(style), len(q), len(xy) // 2, min(xs), min(ys), max(xs), max(ys)))
                for p in q:
                    xy += list(p)
        pts = []
        for p in d['p']:
            kind = p[0]
            if kind.startswith('pl:'):
                kk = 3 if any(t in kind for t in ('town', 'city')) else 4 if any(t in kind for t in ('village', 'suburb')) else 5
            elif kind in KINDS:
                kk = KINDS[kind]
            else:
                continue
            px, py = round((p[2] - lon0) / UNIT), round((p[3] - lat0) / UNIT)
            if not (0 <= px < 65536 and 0 <= py < 65536):
                continue
            pts.append((kk, px, py, p[1] if kk >= 3 else ''))
        w = math.ceil((bb[2] * 1e5 - lon0) / UNIT) + 1; h = math.ceil((bb[3] * 1e5 - lat0) / UNIT) + 1
        v = [round((view[0] * 1e5 - lon0) / UNIT), round((view[1] * 1e5 - lat0) / UNIT),
             round((view[2] * 1e5 - lon0) / UNIT), round((view[3] * 1e5 - lat0) / UNIT)]
        n = key.upper().replace('-', '_')
        lines_out.append(f'static const uint16_t {n}_XY[] = {{')
        for i in range(0, len(xy), 16):
            lines_out.append('  ' + ','.join(map(str, xy[i:i + 16])) + ',')
        lines_out.append('};')
        lines_out.append(f'static const Line {n}_LINES[] = {{')
        for ln in lines:
            lines_out.append('  {%d,%d,%d,%d,%d,%d,%d},' % ln)
        lines_out.append('};')
        lines_out.append(f'static const Point {n}_POINTS[] = {{')
        for kk, px, py, name in pts:
            lines_out.append(f'  {{{kk},{px},{py},"{esc(name)}"}},')
        lines_out.append('};')
        infos.append(f'  {{"{key}", "{esc(names[key])}", {lon0}, {lat0}, {w}, {h}, {v[0]}, {v[1]}, {v[2]}, {v[3]}, '
                     f'{n}_LINES, {len(lines)}, {n}_XY, {n}_POINTS, {len(pts)}}},')
        total += len(xy) * 2 + len(lines) * 16 + len(pts) * 12
    lines_out.append('static const Map MAPS[] = {')
    lines_out += infos
    lines_out += ['};', 'constexpr int MAP_COUNT = sizeof(MAPS) / sizeof(MAPS[0]);',
                  f'constexpr unsigned APPROX_BYTES = {total};', '}', '']
    return '\n'.join(lines_out), total


if __name__ == '__main__':
    text, total = build()
    if '--check' in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit('MapData.h passt nicht zu web/map; python3 tools/gen_device_map.py ausführen')
        print(f'T-Deck-Karten passen zu den Webkarten (ca. {total} Bytes)')
    else:
        OUT.write_text(text)
        print(f'{OUT.relative_to(ROOT)}: ca. {total} Bytes')
