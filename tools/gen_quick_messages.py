#!/usr/bin/env python3
"""Generate the T-Deck's presets/places from the existing web UI (single source)."""
import ast
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
web = (ROOT / 'web/index.html').read_text()
values = {}
for key in ('QUICK', 'PLACES'):
    values[key] = ast.literal_eval(re.search(r'const ' + key + r'=(.*?);', web).group(1))
quote = lambda text: json.dumps(text, ensure_ascii=False)
lines = ['#pragma once', '// Generated by tools/gen_quick_messages.py from web/index.html.',
         'namespace quick {', 'struct Preset { const char* kind; const char* text; const char* label; };',
         'static const Preset PRESETS[] = {']
for kind, text, _icon, label in values['QUICK']:
    lines.append('  {' + ', '.join(map(quote, ({'H': 'HILFE', 'I': 'INFO', 'A': 'ANGEBOT'}[kind], text, label))) + '},')
lines += ['};', 'struct Place { const char* name; double lat, lon; };', 'static const Place PLACES[] = {']
for name, lat, lon in values['PLACES']:
    lines.append(f'  {{{quote(name)}, {lat:.4f}, {lon:.4f}}},')
lines += ['};', '}', '']
out = ROOT / 'examples/companion_radio/ui-brand/QuickData.h'
text = '\n'.join(lines)
if '--check' in sys.argv:
    if not out.exists() or out.read_text() != text:
        sys.exit('QuickData.h differs from web UI; run python3 tools/gen_quick_messages.py')
    print('T-Deck presets and places match web UI')
else:
    out.write_text(text)
